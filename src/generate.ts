import * as vscode from 'vscode';
import { execFile } from 'child_process';

const PROMPT = 'Follow the full-scan procedure in .features/RULES.md and create the feature list for this project.';
const INSTALL_URL = 'https://code.claude.com/docs';
const DECLINED_KEY = 'hlens.generateDeclined';

export function hasClaude(): Promise<boolean> {
  const cmd = process.platform === 'win32' ? 'where' : 'which';
  return new Promise((resolve) => execFile(cmd, ['claude'], (err) => resolve(!err)));
}

/** Runs the user's own Claude Code in a terminal. The extension never handles logins or tokens. */
export async function runGenerate(root: string, ensureInit: () => void) {
  if (!(await hasClaude())) {
    const pick = await vscode.window.showWarningMessage(
      'The feature list is generated by your own Claude Code. Install it and sign in first.',
      'Open install guide',
    );
    if (pick) vscode.env.openExternal(vscode.Uri.parse(INSTALL_URL));
    return;
  }
  ensureInit();
  const terminal = vscode.window.createTerminal({ name: 'HLens', cwd: root });
  terminal.show();
  terminal.sendText(`claude --permission-mode acceptEdits "${PROMPT}"`);
}

/**
 * Asks once when a project has not been set up yet.
 * It does not scan existing code: it only adds the rules (.features/RULES.md),
 * and features appear in the list from the moment you ask your agent to build them.
 */
export async function offerFirstRun(
  context: vscode.ExtensionContext,
  root: string,
  isSetUp: boolean,
  setUp: () => void,
) {
  if (isSetUp || context.workspaceState.get(DECLINED_KEY)) return;

  const auto = vscode.workspace.getConfiguration('hlens').get<boolean>('autoSetup');
  if (auto) return setUp();

  const pick = await vscode.window.showInformationMessage(
    'Set up HLens in this project? It adds .features/RULES.md and a one-line reference in CLAUDE.md. Features show up here as you ask your agent to build them.',
    'Set up',
    'Not in this project',
  );
  if (pick === 'Set up') return setUp();
  if (pick === 'Not in this project') context.workspaceState.update(DECLINED_KEY, true);
}

/** Creates a missing scenario file with the user's own Claude Code. */
export async function runScenarioGenerate(root: string, id: string, file: string, platform: string) {
  if (!(await hasClaude())) {
    const pick = await vscode.window.showWarningMessage(
      'Scenarios are generated by your own Claude Code. Install it and sign in first.',
      'Open install guide',
    );
    if (pick) vscode.env.openExternal(vscode.Uri.parse(INSTALL_URL));
    return;
  }
  const prompt = `Create .features/${id}/${file}. Follow the scenario rules in .features/RULES.md (platform: ${platform}) and .features/${id}/intent.md. Do not modify source code.`;
  const terminal = vscode.window.createTerminal({ name: 'HLens', cwd: root });
  terminal.show();
  terminal.sendText(`claude --permission-mode acceptEdits "${prompt}"`);
}
